static string Normalize(string content) => content.Replace("\r\n", "\n", StringComparison.Ordinal).TrimEnd();

static List<Package> ListPackages()
{
    var info = new ProcessStartInfo("dotnet", ["list", Project, "package", "--include-transitive", "--format", "json"]) { RedirectStandardOutput = true };
    using var process = Process.Start(info)!;
    var json = process.StandardOutput.ReadToEnd();
    process.WaitForExit();
    if (process.ExitCode != 0)
    {
        throw new InvalidOperationException($"dotnet list package failed ({process.ExitCode}); build the solution first.");
    }

    using var document = JsonDocument.Parse(json);
    return document.RootElement.GetProperty("projects").EnumerateArray()
        .SelectMany(p => p.GetProperty("frameworks").EnumerateArray())
        .SelectMany(f => new[] { "topLevelPackages", "transitivePackages" }.SelectMany(k => f.TryGetProperty(k, out var list) ? list.EnumerateArray() : []))
        .Select(p => new Package(p.GetProperty("id").GetString()!, p.GetProperty("resolvedVersion").GetString()!))
        .DistinctBy(p => p.Id)
        .OrderBy(p => p.Id, StringComparer.Ordinal)
        .ToList();
}

static string PackagesFolder() =>
    Environment.GetEnvironmentVariable("NUGET_PACKAGES") is { Length: > 0 } custom
        ? custom
        : Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.UserProfile), ".nuget", "packages");

record Package(string Id, string Version);

record Component(string Name, string Url, string[] Prefixes, string? License, string[] Files);
