// Writes THIRD-PARTY-NOTICES.txt: the licences and copyright notices of everything bundled into MicControl.exe, which
// their (MIT, BSD and similar) licences require to travel with it. The setup installs the file next to the exe.
// Run from the repository root after changing packages:  dotnet run tools/GenerateThirdPartyNotices.cs
// With --check it only compares (CI runs that), and fails if the file is out of date.
//
// Packages come from `dotnet list package --include-transitive` for the shipped project; their notice files come from
// the NuGet cache. A package that no component below claims fails the run, so a new dependency can't ship without
// its notice: add it to Components (or to BuildOnly when nothing of it ends up in the exe).

using System.Diagnostics;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;

const string Project = "Sources/MicControl/MicControl.csproj";
const string Output = "THIRD-PARTY-NOTICES.txt";
var check = args.Contains("--check");

// Build-time only: nothing of these is in the exe.
string[] buildOnly = ["Avalonia.BuildServices"];

Component[] components =
[
    new(".NET runtime and libraries", "https://github.com/dotnet/runtime", ["Microsoft.Extensions.", "System."],
        Mit(".NET Foundation and Contributors"), ["THIRD-PARTY-NOTICES.TXT"]),
    new("Avalonia", "https://github.com/AvaloniaUI/Avalonia", ["Avalonia"], Mit("2013-2026 The AvaloniaUI Project"), []),
    new("ANGLE (Avalonia.Angle.Windows.Natives)", "https://github.com/google/angle", ["Avalonia.Angle.Windows.Natives"], null, ["LICENSE"]),
    new("SkiaSharp and HarfBuzzSharp, with Skia, HarfBuzz and their libraries", "https://github.com/mono/SkiaSharp",
        ["SkiaSharp", "HarfBuzzSharp"], null, ["LICENSE.txt", "THIRD-PARTY-NOTICES.txt"]),
    new("MicroCom", "https://github.com/kekekeks/MicroCom", ["MicroCom."], Mit("2021 Nikita Tsukanov"), []),
    new("Tmds.DBus", "https://github.com/tmds/Tmds.DBus", ["Tmds.DBus"], Mit("Tom Deseyn"), []),
    new("CommunityToolkit.Mvvm", "https://github.com/CommunityToolkit/dotnet", ["CommunityToolkit.Mvvm"], null, ["License.md", "ThirdPartyNotices.txt"]),
    new("NAudio", "https://github.com/naudio/NAudio", ["NAudio"], Mit("2023 Mark Heath"), []),
];

var packages = ListPackages();
var cache = PackagesFolder();
var unclaimed = packages.Where(p => !buildOnly.Contains(p.Id) && Claim(p.Id) is null).Select(p => p.Id).ToList();
if (unclaimed.Count > 0)
{
    Console.Error.WriteLine($"No notice entry for: {string.Join(", ", unclaimed)}. Add them to Components in tools/GenerateThirdPartyNotices.cs.");
    return 1;
}

var text = new StringBuilder();
text.Append("""
    MicControl third-party notices

    MicControl itself is licensed under the GNU General Public License, version 3 or (at your option) any later version
    (see LICENSE.txt). It includes the following software, each under its own licence, given in full below. Generated by
    tools/GenerateThirdPartyNotices.cs.


    """);

var seen = new HashSet<string>(StringComparer.Ordinal);
foreach (var component in components)
{
    var used = packages.Where(p => !buildOnly.Contains(p.Id) && Claim(p.Id) == component).ToList();
    if (used.Count == 0)
    {
        continue;
    }

    text.Append(new string('=', 120)).Append('\n');
    text.Append(component.Name).Append('\n').Append(component.Url).Append('\n');
    text.Append("Packages: ").Append(string.Join(", ", used.Select(p => $"{p.Id} {p.Version}"))).Append("\n\n");
    if (component.License is { } license)
    {
        text.Append(license).Append("\n\n");
    }

    foreach (var fileName in component.Files)
    {
        // The first package of the component that carries the file; identical files (shared notices) appear once.
        var path = used.Select(p => Path.Combine(cache, p.Id.ToLowerInvariant(), p.Version.ToLowerInvariant(), fileName)).FirstOrDefault(File.Exists)
            ?? throw new InvalidOperationException($"{component.Name}: no package has {fileName}");
        var content = Normalize(File.ReadAllText(path));
        if (seen.Add(Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(content)))))
        {
            text.Append(content).Append("\n\n");
        }
    }
}

text.Append(new string('=', 120)).Append('\n');
text.Append("Fluent UI System Icons (the bundled icon font)\nhttps://github.com/microsoft/fluentui-system-icons\n\n");
text.Append(Normalize(File.ReadAllText("Sources/MicControl.UI/Assets/Fonts/LICENSE.txt"))).Append('\n');

var result = text.ToString();
if (check)
{
    var current = File.Exists(Output) ? Normalize(File.ReadAllText(Output)) + "\n" : "";
    if (current != result)
    {
        Console.Error.WriteLine($"{Output} is out of date: run  dotnet run tools/GenerateThirdPartyNotices.cs  and commit it.");
        return 1;
    }

    Console.WriteLine($"{Output} is up to date ({packages.Count} packages).");
    return 0;
}

File.WriteAllText(Output, result);
Console.WriteLine($"Wrote {Output} ({packages.Count} packages, {result.Length / 1024} KB).");
return 0;

// The component with the longest matching prefix, so "Avalonia.Angle.Windows.Natives" is ANGLE, not Avalonia.
Component? Claim(string id) => components
    .Select(c => (Component: c, Match: c.Prefixes.Where(p => id.StartsWith(p, StringComparison.Ordinal)).Select(p => p.Length).DefaultIfEmpty(0).Max()))
    .Where(c => c.Match > 0)
    .OrderByDescending(c => c.Match)
    .Select(c => c.Component)
    .FirstOrDefault();

